// Hand-authored pixel scenes. Rows are padded to the widest line at render
// time, so these can be edited as pictures without counting characters.
//
//   .  transparent      #  ink        o  spot (magenta)
//   c  cyan             a  acid       y  amber

const PALETTE: Record<string, string> = {
  "#": "var(--ink)",
  o: "var(--spot)",
  c: "var(--cyan)",
  a: "var(--acid)",
  y: "var(--amber)",
};

function Scene({ rows, className = "" }: { rows: string[]; className?: string }) {
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const cells: React.ReactElement[] = [];
  for (let y = 0; y < h; y++) {
    const row = rows[y].padEnd(w, ".");
    for (let x = 0; x < w; x++) {
      const ch = row[x];
      const fill = PALETTE[ch];
      if (!fill) continue;
      cells.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />);
    }
  }
  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      className={`pixelated w-full ${className}`}
      preserveAspectRatio="xMidYMid meet"
      aria-hidden="true"
    >
      {cells}
    </svg>
  );
}

